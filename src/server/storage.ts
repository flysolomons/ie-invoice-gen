import "server-only";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { del, get, put } from "@vercel/blob";
import { env } from "@/env";

/**
 * File storage for uploaded receipts. The database stores only the key; files
 * are always served through an authenticated route, never by public URL.
 */
export interface FileStorage {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<{ body: ReadableStream | Uint8Array<ArrayBuffer> } | null>;
  delete(key: string): Promise<void>;
}

/** Keys are generated by the server, but validate anyway (no path traversal). */
const SAFE_KEY = /^[a-z0-9]+(?:\/[a-z0-9-]+)*\.[a-z0-9]+$/;
function assertKey(key: string) {
  if (!SAFE_KEY.test(key)) throw new Error(`Invalid storage key: ${key}`);
}

/** Development: files under ./.uploads (git-ignored). Not usable on Vercel. */
class LocalStorage implements FileStorage {
  private root = path.join(process.cwd(), ".uploads");
  private file(key: string) {
    assertKey(key);
    return path.join(this.root, ...key.split("/"));
  }
  async put(key: string, data: Buffer) {
    const file = this.file(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, data);
  }
  async get(key: string) {
    try {
      return { body: new Uint8Array(await readFile(this.file(key))) };
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw e;
    }
  }
  async delete(key: string) {
    await rm(this.file(key), { force: true });
  }
}

/** Production: private Vercel Blob store (needs BLOB_READ_WRITE_TOKEN). */
class VercelBlobStorage implements FileStorage {
  async put(key: string, data: Buffer, contentType: string) {
    assertKey(key);
    await put(key, data, { access: "private", contentType, addRandomSuffix: false });
  }
  async get(key: string) {
    assertKey(key);
    const result = await get(key, { access: "private" });
    return result?.stream ? { body: result.stream } : null;
  }
  async delete(key: string) {
    assertKey(key);
    await del(key);
  }
}

/** Read a stored file fully into memory (for small files such as the logo). */
export async function readStoredFile(key: string): Promise<Buffer | null> {
  const file = await getStorage().get(key);
  if (!file) return null;
  return file.body instanceof Uint8Array
    ? Buffer.from(file.body)
    : Buffer.from(await new Response(file.body).arrayBuffer());
}

let storage: FileStorage | null = null;

export function getStorage(): FileStorage {
  if (!storage) {
    const driver = env.STORAGE_DRIVER ?? (env.BLOB_READ_WRITE_TOKEN ? "vercel-blob" : "local");
    if (driver === "local" && process.env.VERCEL) {
      throw new Error("Local file storage doesn't work on Vercel. Connect a Blob store.");
    }
    storage = driver === "vercel-blob" ? new VercelBlobStorage() : new LocalStorage();
  }
  return storage;
}
